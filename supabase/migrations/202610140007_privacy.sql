create function public.fulfill_deletion(request uuid,operator uuid) returns void language plpgsql security definer set search_path='' as $$declare student uuid;college uuid;begin
select owner_id,college_id into student,college from public.privacy_requests where id=request and kind='delete' and status='pending' for update;
if student is null then raise exception 'Pending request required';end if;
if not exists(select 1 from public.profiles where id=operator and college_id=college and role='admin') then raise exception 'College admin required';end if;
insert into public.moderation_actions(college_id,actor_id,action,target_id,reason) values(college,operator,'fulfill_account_deletion',student,'Student requested account deletion; files removed before database deletion');
delete from public.posts where id in(select post_id from private.post_authors where user_id=student);
delete from private.rate_events where user_id=student;
delete from private.delivery_keys where owner_id=student;
delete from auth.users where id=student;
end$$;
revoke all on function public.fulfill_deletion(uuid,uuid) from public,anon,authenticated;
grant execute on function public.fulfill_deletion(uuid,uuid) to service_role;
